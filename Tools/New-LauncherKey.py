"""Round 8: 7: The Observer's own launcher publisher key, made ONCE. Creates (or reuses, if it already exists) the private key in
Builds/PublisherPrivate/launcher-signing.pem (git-ignored; never printed, copied, deleted or replaced) and pins only the public key into the
launcher source (Launcher/pinned-key.json, Launcher/pinned_key.hpp). Every launcher ever shipped trusts only this key: losing or replacing it
means players must reinstall from a new starter package."""
from pathlib import Path
from cryptography.hazmat.primitives.asymmetric import rsa
from cryptography.hazmat.primitives import serialization
import hashlib,json
root=Path(__file__).resolve().parents[1]
private=root/'Builds/PublisherPrivate/launcher-signing.pem'
private.parent.mkdir(parents=True,exist_ok=True)
if private.exists():
    key=serialization.load_pem_private_key(private.read_bytes(),password=None)
    made=False
else:
    key=rsa.generate_private_key(public_exponent=65537,key_size=3072)
    private.write_bytes(key.private_bytes(serialization.Encoding.PEM,serialization.PrivateFormat.PKCS8,serialization.NoEncryption()))
    made=True
public=key.public_key();numbers=public.public_numbers()
der=public.public_bytes(serialization.Encoding.DER,serialization.PublicFormat.SubjectPublicKeyInfo)
record={'algorithm':'RSA-PKCS1-SHA256','keyId':hashlib.sha256(der).hexdigest(),
        'modulusHex':format(numbers.n,'x'),'exponentHex':format(numbers.e,'06x')}
(root/'Launcher/pinned-key.json').write_text(json.dumps(record,indent=2))
(root/'Launcher/pinned_key.hpp').write_text('#pragma once\n// Generated by Tools/New-LauncherKey.py: the public half of the publisher key (the private half never leaves Builds/PublisherPrivate/).\nnamespace wr {\ninline constexpr const char* KeyId="'+record['keyId']+'";\ninline constexpr const char* ModulusHex="'+record['modulusHex']+'";\ninline constexpr const char* ExponentHex="'+record['exponentHex']+'";\n}\n')
print('Public key ID:',record['keyId'])
print(('New' if made else 'Existing')+' private publisher key kept only in git-ignored storage:',private)
