"""Round 18: the Cattalus chapter's dialogue as data (a copy of make_biaveh_lines.py).

Usage (repo root): python Tools/Voice/make_cattalus_lines.py
Reads Docs/CHAPTER_CATTALUS.md (Dan's script CAT_01..CAT_12 + "Proposed lines (Round 18, Code)") and writes
  Unity/Assets/Resources/Cattalus/cattalus_dialogue.json  (loaded at runtime)
  Docs/CATTALUS-LINES.md                                   (the line list for Dan)
Every table row "| CAT_.. | Speaker | Dialogue | Performance |" is a line; rows whose dialogue is "—" are beats (no line).
Scene id = the id up to its second "_" (CAT_08W_01 -> CAT_08W).
Speakers: 7 -> seven, Panther -> cat, Acquaintance -> juniper (label "Juniper"), Champion -> duchess (label "Duchess"),
Steward -> steward, Announcer -> announcer (the Barker voice). Every cat is telepathic in Unity (the announcer = the PA).
Race lines (CAT_07_*) and practice tips (CAT_06_01) are marked "repeat" (a restart / the practice lap plays them again).
"""
import json, os, re

ROOT = os.getcwd()
SRC = os.path.join(ROOT, "Docs", "CHAPTER_CATTALUS.md")
OUT = os.path.join(ROOT, "Unity", "Assets", "Resources", "Cattalus", "cattalus_dialogue.json")
DOC = os.path.join(ROOT, "Docs", "CATTALUS-LINES.md")
SPK = {"7": ("seven", "7", "Seven"), "Panther": ("cat", "Panther", "Cat"), "Acquaintance": ("juniper", "Juniper", "juniper"),
       "Juniper": ("juniper", "Juniper", "juniper"), "Champion": ("duchess", "Duchess", "Duchess"), "Duchess": ("duchess", "Duchess", "Duchess"),
       "Steward": ("steward", "Steward", "steward"), "Announcer": ("announcer", "Announcer", "TeedOff Barker")}
VOCAL = ("laugh", "giggle", "chuckle", "exhale", "sigh", "breath", "snort", "hum", "dry", "soft", "quiet", "low", "amused",
         "gentle", "warm", "tired", "urgent", "firm", "flat", "curious", "innocent", "delighted", "wonder", "practical", "breathless",
         "patient", "measured", "serious", "pointed", "honest", "calm", "light", "wry", "relief", "reassur", "dignified", "composed",
         "precise", "sincere", "reflect", "impressed", "disbelie", "casual", "matter", "mild", "softly", "suppressed", "pleased",
         "smile", "teasing", "affection", "enthusias", "excite", "frustrat", "encourag", "wistful", "proud", "pride", "resolute",
         "startled", "content", "plain", "confident", "professional", "earnest", "guarded", "knowing", "fond", "playful", "absurd",
         "sporting", "interested", "satisf", "relaxed", "purr", "comfortable", "thoughtful", "challenge", "happy", "grandeur")
STAGE = ("leans", "looks", "glances", "turns", "steps", "holds", "points", "moves", "stops", "watches", "indicates", "camera",
         "his ", "her hand", "kneels", "mounts", "runs", "settles", "gesture", "fingers", "tail", "eyes", "approaches", "checks",
         "walks", "begins", "places", "peers", "nudges", "arranges", "traces", "brings", "selects", "takes", "studies", "rotates",
         "recogni", "before", "after", "the lights", "either", "presents", "slides", "where", "objective", "wrong state")
REPEAT = re.compile(r"^CAT_07_|^CAT_06_01$|^CAT_11_03$|^CAT_08L_05$")   # CAT_11_03 repeats CAT_04_13's words ("Heh. Come on.")
row = re.compile(r"^\|\s*(CAT_\w+?)\s*\|\s*([^|]+?)\s*\|\s*(.+?)\s*\|\s*(.*?)\s*\|$")
head = re.compile(r"^#{2,4}\s+(CAT_\w+?)\s+—\s+(.+?)\s*$")


def vocal(cell):
    keep = []
    for p in re.split(r"[;.]", cell):
        q = p.strip().lower()
        words = re.findall(r"[a-z]+", q)
        if q and any(any(x.startswith(w) for x in words) for w in VOCAL) and not any(w in q for w in STAGE):
            keep.append(p.strip())
    t = ", ".join(k for k in keep if k)
    t = re.sub(r"\s*\(.*?\)", "", t)
    return t.strip(" ,")


lines, seen, titles, unknown = [], set(), {}, []
for raw in open(SRC, encoding="utf-8").read().replace("\r\n", "\n").split("\n"):
    h = head.match(raw.strip())
    if h and h.group(1) not in titles: titles[h.group(1)] = h.group(2)
    m = row.match(raw.strip())
    if not m: continue
    lid, who, said, act = m.groups()
    if who in ("—", "-") or said.strip() in ("—", "-"): continue
    if lid in seen: continue
    seen.add(lid)
    sid = "_".join(lid.split("_")[:2])
    if who not in SPK: unknown.append(f"{lid} ({who})"); continue
    speaker, label, voice = SPK[who]
    lines.append({"id": lid, "scene": sid, "speaker": speaker, "label": label, "text": said, "direction": vocal(act), "action": act,
                  "voice": voice, "repeat": bool(REPEAT.match(lid))})

scenes = []
for l in lines:
    if not any(s["id"] == l["scene"] for s in scenes): scenes.append({"id": l["scene"], "title": titles.get(l["scene"], l["scene"]), "round": 18})
os.makedirs(os.path.dirname(OUT), exist_ok=True)
json.dump({"scenes": scenes, "lines": lines}, open(OUT, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
with open(DOC, "w", encoding="utf-8") as f:
    f.write("# Cattalus — the lines (generated by Tools/Voice/make_cattalus_lines.py from Docs/CHAPTER_CATTALUS.md)\n\n")
    f.write("Voices: 7 = Seven (Eleven v3, performance notes as audio tags) · Panther = Cat · Juniper = Dan's saved \"juniper\" · "
            "Duchess = Dan's saved \"Duchess\" · Steward = Dan's saved \"steward\" · the Announcer (+ every Cat-a-tron advert) = "
            "\"TeedOff Barker\" from Tee'd Off (Eleven v3). Cats are telepathic in Unity; the announcer is the square's PA "
            "(`Tools/Voice/generate_cattalus_voices.py`). Files: `Unity/Assets/Resources/CattalusVoice/<id>.mp3`. "
            "`_P` / `_CALL` ids = Code's proposed lines (Dan to review).\n\n")
    for sc in scenes:
        ls = [l for l in lines if l["scene"] == sc["id"]]
        f.write(f"## {sc['id']} — {sc['title']}\n\n| id | speaker | line | direction |\n|---|---|---|---|\n")
        for l in ls: f.write(f"| `{l['id']}` | {l['label']} | {l['text']} | {l['direction']} |\n")
        f.write("\n")
print(f"{len(scenes)} scenes, {len(lines)} lines -> {OUT}")
for sc in scenes: print(sc["id"], len([l for l in lines if l["scene"] == sc["id"]]), sc["title"])
if unknown: print("UNKNOWN SPEAKERS (skipped):", unknown)
