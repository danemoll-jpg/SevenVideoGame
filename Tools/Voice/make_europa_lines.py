"""Round 14: Europa's dialogue as data.

Usage (repo root): python Tools/Voice/make_europa_lines.py
Reads Docs/CHAPTER_EUROPA.md (Dan's spec, sections 1-17) and writes
  Unity/Assets/Resources/Europa/europa_dialogue.json  (scenes + lines, loaded by EuropaDialogue at runtime)
  Docs/EUROPA-LINES.md                                (the line list with ids, for Dan)
Line ids: EUR_<scene>_<nn>. Scenes are the spec's sections (EUR_01 ... EUR_17); section 5's race lines are split into
EUR_05R (registration), EUR_05O (clean overtake), EUR_05L (after a loss), EUR_05W (after a win), EUR_05E (the pulse after).
"**7 — softly:** Oh..." keeps "softly" as the delivery direction (Eleven v3 tag for 7 / Panther).
Speakers: 7 -> seven (voice "Seven"), PANTHER -> cat ("Cat", label Panther, telepathic), KEEPER -> keeper ("Keeper"),
TUNNELER -> tunneler ("Tunneler"), SCREE WORKER -> scree (a premade voice, see generate_europa_voices.py).
"""
import json, os, re

ROOT = os.getcwd()
SRC = os.path.join(ROOT, "Docs", "CHAPTER_EUROPA.md")
OUT = os.path.join(ROOT, "Unity", "Assets", "Resources", "Europa", "europa_dialogue.json")
DOC = os.path.join(ROOT, "Docs", "EUROPA-LINES.md")
SPK = {"7": ("seven", "7", "Seven"), "PANTHER": ("cat", "Panther", "Cat"), "KEEPER": ("keeper", "Keeper", "Keeper"),
       "TUNNELER": ("tunneler", "Tunneler", "Tunneler"), "SCREE WORKER": ("scree", "Scree worker", "scree")}
TITLES = {}
# QF13 (18): the bike talk aboard (EUR_16_01..03) is cut from the spec; the reunion line "Good." keeps its id EUR_16_04
# (and its voice file), so numbering in that scene starts after the cut lines
START = {"EUR_16": 3}

text = open(SRC, encoding="utf-8").read().replace("\r\n", "\n")
scenes, lines = [], []
sec, sub, n = None, None, {}
line_re = re.compile(r"^\*\*(7|PANTHER|KEEPER|TUNNELER|SCREE WORKER)(?:\s*[—-]\s*([^:*]+?))?:\*\*\s*(.+)$")
for raw in text.split("\n"):
    s = raw.strip()
    m = re.match(r"^\*\*(\d+)\.\s+(.+?)\*\*$", s)
    if m:
        sec = int(m.group(1)); sub = None
        sid = f"EUR_{sec:02d}"
        scenes.append({"id": sid, "title": m.group(2).capitalize(), "round": 14}); continue
    if sec == 5:
        u = s.upper()
        if u.startswith("**AT REGISTRATION"): sub = "R"
        elif u.startswith("**DURING A CLEAN OVERTAKE"): sub = "O"
        elif u.startswith("**AFTER A LOSS"): sub = "L"
        elif u.startswith("**AFTER A WIN"): sub = "W"
        elif "EXTRACTION PULSE" in u: sub = "E"
    m = line_re.match(s)
    if not m or sec is None: continue
    who, direction, said = m.group(1), (m.group(2) or "").strip(), m.group(3).strip()
    sid = f"EUR_{sec:02d}" + (sub if sec == 5 and sub else "")
    if sec == 5 and sub and not any(x["id"] == sid for x in scenes):
        scenes.append({"id": sid, "title": {"R": "Race registration", "O": "Race: clean overtake", "L": "Race: after a loss", "W": "Race: after a win", "E": "After the race"}[sub], "round": 14})
    n[sid] = n.get(sid, START.get(sid, 0)) + 1
    speaker, label, voice = SPK[who]
    lines.append({"id": f"{sid}_{n[sid]:02d}", "scene": sid, "speaker": speaker, "label": label, "text": said,
                  "direction": direction, "voice": voice, "delivery": "", "cue": ""})

os.makedirs(os.path.dirname(OUT), exist_ok=True)
json.dump({"scenes": scenes, "lines": lines}, open(OUT, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
with open(DOC, "w", encoding="utf-8") as f:
    f.write("# Europa — the lines (generated by Tools/Voice/make_europa_lines.py from Docs/CHAPTER_EUROPA.md)\n\n")
    f.write("Voices: 7 = Seven (Eleven v3, directions as audio tags) · Panther = Cat (telepathic treatment in Unity) · Keeper = "
            "Keeper (with a soft whale-call layer + underwater reverb in Unity) · Tunneler = Tunneler · Scree worker = a premade "
            "voice (Scree noise layered under it in Unity). Files: `Unity/Assets/Resources/EuropaVoice/<id>.mp3`.\n\n")
    cur = None
    for l in lines:
        if l["scene"] != cur:
            cur = l["scene"]; t = next(s["title"] for s in scenes if s["id"] == cur)
            f.write(f"\n## {cur} — {t}\n\n| id | who | line | direction |\n| --- | --- | --- | --- |\n")
        f.write(f'| `{l["id"]}` | {l["label"]} | {l["text"]} | {l["direction"]} |\n')
print(f"{len(scenes)} scenes, {len(lines)} lines -> {OUT}")
for sc in scenes: print(sc["id"], sum(1 for l in lines if l["scene"] == sc["id"]), sc["title"])
