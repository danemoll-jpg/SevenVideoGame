"""Round 16: the asteroid chapter's dialogue as data.

Usage (repo root): python Tools/Voice/make_asteroid_lines.py
Reads Docs/CHAPTER_ASTEROID.md (Dan's script AST_01..AST_11 + the "Proposed lines (Round 16)" table) and writes
  Unity/Assets/Resources/Asteroid/asteroid_dialogue.json  (loaded by AsteroidDialogue at runtime)
  Docs/ASTEROID-LINES.md                                   (the line list for Dan)
Every table row "| AST_.. | Speaker | Dialogue | Performance |" is a line; rows whose dialogue is "—" are beats (no line).
Scene id = the id up to its second "_" (AST_11A_01 -> AST_11A; AST_08_05S -> AST_08).
Speakers: 7 -> seven (voice "Seven", v3 + tags), Panther -> cat ("Cat", telepathic), Machinist -> machinist (Dan's saved
voice "Machinist"), System -> system (a premade voice picked by generate_asteroid_voices.py).
"""
import json, os, re

ROOT = os.getcwd()
SRC = os.path.join(ROOT, "Docs", "CHAPTER_ASTEROID.md")
OUT = os.path.join(ROOT, "Unity", "Assets", "Resources", "Asteroid", "asteroid_dialogue.json")
DOC = os.path.join(ROOT, "Docs", "ASTEROID-LINES.md")
SPK = {"7": ("seven", "7", "Seven"), "Panther": ("cat", "Panther", "Cat"), "Machinist": ("machinist", "Machinist", "Machinist"),
       "System": ("system", "System", "system")}
TITLES = {"AST_01": "Something on the rock", "AST_02": "Receiving", "AST_03": "The city that still works", "AST_04": "The Machinist",
          "AST_05": "Keeping the wrong thing alive", "AST_06": "A missed answer", "AST_07": "The caretaker's objection",
          "AST_08": "What the machines were for", "AST_09": "A different instruction", "AST_10": "Back aboard",
          "AST_11A": "Next destination (Biaveh unfinished)", "AST_11B": "Next destination (Biaveh complete: the Cattalus lead)"}
VOCAL = ("laugh", "giggle", "chuckle", "exhale", "sigh", "breath", "snort", "hum", "dry", "soft", "quiet", "low", "amused",
         "gentle", "warm", "tired", "urgent", "tight", "frightened", "firm", "flat", "curious", "innocent", "delighted", "wonder",
         "practical", "focused", "exertion", "breathless", "patient", "measured", "serious", "pointed", "honest", "calm", "light", "wry")
STAGE = ("leans", "looks", "glances", "turns", "steps", "holds", "points", "moves", "blocks", "stops", "scans", "waits", "searches",
         "pushes", "lifts", "places", "finds", "rubs", "selects", "brings", "sits", "watches", "indicates", "lets", "camera", "his ",
         "her hand", "conveyor", "studying", "she handles", "looking at")
row = re.compile(r"^\|\s*(AST_\w+?)\s*\|\s*(7|Panther|Machinist|System|—)\s*\|\s*(.+?)\s*\|\s*(.*?)\s*\|$")

def vocal(cell):
    keep = []
    for p in re.split(r"[;.]", cell):
        q = p.strip().lower()
        words = re.findall(r"[a-z]+", q)
        if q and any(any(x.startswith(w) for x in words) for w in VOCAL) and not any(w in q for w in STAGE) and "slows" not in q:
            keep.append(re.sub(r"(?i)telepathic,?\s*", "", p.strip()))
    t = ", ".join(keep)
    t = re.sub(r"\s*\(.*?\)", "", t)
    t = re.split(r",? (?:after|once|without|hauling|followed by)", t)[0] if not t.lower().startswith("sigh") else t
    return t.strip(" ,")

lines, seen = [], set()
for raw in open(SRC, encoding="utf-8").read().replace("\r\n", "\n").split("\n"):
    m = row.match(raw.strip())
    if not m: continue
    lid, who, said, act = m.groups()
    if who == "—" or said.strip() in ("—", "-"): continue
    if lid in seen: continue
    seen.add(lid)
    sid = "_".join(lid.split("_")[:2])
    speaker, label, voice = SPK[who]
    lines.append({"id": lid, "scene": sid, "speaker": speaker, "label": label, "text": said, "direction": vocal(act), "action": act, "voice": voice})

scenes = []
for l in lines:
    if not any(s["id"] == l["scene"] for s in scenes): scenes.append({"id": l["scene"], "title": TITLES.get(l["scene"], l["scene"]), "round": 16})
os.makedirs(os.path.dirname(OUT), exist_ok=True)
json.dump({"scenes": scenes, "lines": lines}, open(OUT, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
with open(DOC, "w", encoding="utf-8") as f:
    f.write("# The Asteroid — the lines (generated by Tools/Voice/make_asteroid_lines.py from Docs/CHAPTER_ASTEROID.md)\n\n")
    f.write("Voices: 7 = Seven (Eleven v3, performance notes as audio tags) · Panther = Cat (telepathic treatment in Unity) · "
            "Machinist = Dan's saved voice \"Machinist\" · System = a premade ElevenLabs voice (`Tools/Voice/generate_asteroid_voices.py`). "
            "Files: `Unity/Assets/Resources/AsteroidVoice/<id>.mp3`. Ids ending in a letter + digit (`_P1`) are the chat's proposed lines.\n\n")
    for sc in scenes:
        ls = [l for l in lines if l["scene"] == sc["id"]]
        f.write(f"## {sc['id']} — {sc['title']}\n\n| id | speaker | line | direction |\n|---|---|---|---|\n")
        for l in ls: f.write(f"| `{l['id']}` | {l['label']} | {l['text']} | {l['direction']} |\n")
        f.write("\n")
print(f"{len(scenes)} scenes, {len(lines)} lines -> {OUT}")
for sc in scenes: print(sc["id"], len([l for l in lines if l["scene"] == sc["id"]]), sc["title"])
