using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEngine;
using L = Seven.MoonLayout;

namespace Seven.EditorTools
{
    /// <summary>
    /// QF3: proof that nothing phantom intrudes into the prison. Run on the built Chapter 1 scene (before it is saved):
    /// 1. every renderer whose triangles reach into a walkable volume (each ground zone, 0.2 m above its floor up to
    ///    2.2 m) - listed with its collider status; renderers without a collider must be intentional props only;
    /// 2. every city (layer 20) triangle that is visible from inside the host structure (front-facing toward the inside
    ///    and inside its volume) - must be 0: the prison, catwalk cavern, passages and ruins live in there.
    /// Report: Docs/Previews/qf3/phantom_check.txt + the build log.
    /// </summary>
    public static partial class FightDemoBuilder
    {
        static void PhantomCheck(Seven.WorldGround wg)
        {
            var sb = new StringBuilder();
            sb.AppendLine("QF3 phantom-wall check (Chapter 1 scene, generated by FightDemoBuilder.PhantomCheck)");
            var vols = wg.Zones.Select(z => (z.Name, new Bounds(
                new Vector3((z.Min.x + z.Max.x) * 0.5f, (Mathf.Min(z.Y0, z.Y1) + Mathf.Max(z.Y0, z.Y1)) * 0.5f + 1.2f, (z.Min.y + z.Max.y) * 0.5f),
                new Vector3(z.Max.x - z.Min.x - 0.1f, Mathf.Abs(z.Y1 - z.Y0) + 2.0f, z.Max.y - z.Min.y - 0.1f)))).ToList();
            var host = new Bounds();
            host.SetMinMax(new Vector3(-114.5f, -119.5f, L.HostFrontZ + 0.5f), new Vector3(144.5f, 28.5f, 79.5f));
            int noCollider = 0, cityHits = 0, cityVisible = 0;
            var rows = new List<string>();
            foreach (var mr in Object.FindObjectsByType<MeshRenderer>(FindObjectsInactive.Include, FindObjectsSortMode.None))
            {
                var mf = mr.GetComponent<MeshFilter>();
                if (mf == null || mf.sharedMesh == null) continue;
                var mesh = mf.sharedMesh; var tr = mr.transform;
                var vs = mesh.vertices; var ts = mesh.triangles;
                for (int i = 0; i < vs.Length; i++) vs[i] = tr.TransformPoint(vs[i]);
                bool city = mr.gameObject.layer == CityLayer;
                var hitZones = new HashSet<string>(); int hitTris = 0, inHostFront = 0;
                for (int i = 0; i < ts.Length; i += 3)
                {
                    Vector3 a = vs[ts[i]], b = vs[ts[i + 1]], c = vs[ts[i + 2]];
                    var tb = new Bounds(a, Vector3.zero); tb.Encapsulate(b); tb.Encapsulate(c);
                    bool hit = false;
                    foreach (var (n, vb) in vols)
                        if (tb.Intersects(vb) && TriBox(a, b, c, vb)) { hitZones.Add(n); hit = true; }
                    if (hit) hitTris++;
                    if (city && tb.Intersects(host) && TriBox(a, b, c, host))
                    {
                        // visible from inside = its front side faces into the volume somewhere: any triangle inside the
                        // host volume counts (single-sided or not, from inside you would see one of its sides)
                        inHostFront++;
                    }
                }
                bool col = mr.GetComponent<Collider>() != null;
                if (hitTris > 0)
                {
                    if (!col) noCollider++;
                    if (city) cityHits++;
                    rows.Add($"  {(col ? "collider   " : "NO COLLIDER")} {GoPath(tr),-60} layer {mr.gameObject.layer,2} {hitTris,5} tris in {string.Join(",", hitZones)}");
                }
                if (inHostFront > 0) { cityVisible += inHostFront; rows.Add($"  CITY INSIDE HOST {GoPath(tr)}: {inHostFront} tris"); }
            }
            sb.AppendLine($"walkable volumes: {vols.Count} zones (floor + 0.2 .. + 2.2 m, ramps included)");
            sb.AppendLine($"renderers reaching into a walkable volume: {rows.Count(r => !r.Contains("CITY INSIDE"))}, of these without a collider: {noCollider}");
            sb.AppendLine($"city (layer {CityLayer}) renderers in a walkable volume: {cityHits} (must be 0)");
            sb.AppendLine($"city triangles inside the host structure (visible from the prison): {cityVisible} (must be 0)");
            foreach (var r in rows.OrderBy(r => r)) sb.AppendLine(r);
            var dir = System.IO.Path.Combine(ProjectRoot, "..", "Docs", "Previews", "qf3");
            Directory.CreateDirectory(dir);
            File.WriteAllText(System.IO.Path.Combine(dir, "phantom_check.txt"), sb.ToString());
            foreach (var line in sb.ToString().Split('\n').Take(6)) Log("phantom check: " + line.TrimEnd());
        }

        static string GoPath(Transform t) => t.parent == null ? t.name : GoPath(t.parent) + "/" + t.name;

        /// <summary>Triangle vs. axis-aligned box (separating axis test).</summary>
        static bool TriBox(Vector3 a, Vector3 b, Vector3 c, Bounds box)
        {
            var cen = box.center; var h = box.extents;
            Vector3 v0 = a - cen, v1 = b - cen, v2 = c - cen;
            Vector3 e0 = v1 - v0, e1 = v2 - v1, e2 = v0 - v2;
            var axes = new List<Vector3> { Vector3.right, Vector3.up, Vector3.forward, Vector3.Cross(e0, e1) };
            foreach (var e in new[] { e0, e1, e2 })
                foreach (var u in new[] { Vector3.right, Vector3.up, Vector3.forward }) axes.Add(Vector3.Cross(u, e));
            foreach (var ax in axes)
            {
                if (ax.sqrMagnitude < 1e-12f) continue;
                float p0 = Vector3.Dot(v0, ax), p1 = Vector3.Dot(v1, ax), p2 = Vector3.Dot(v2, ax);
                float r = h.x * Mathf.Abs(ax.x) + h.y * Mathf.Abs(ax.y) + h.z * Mathf.Abs(ax.z);
                if (Mathf.Min(p0, Mathf.Min(p1, p2)) > r || Mathf.Max(p0, Mathf.Max(p1, p2)) < -r) return false;
            }
            return true;
        }
    }
}
